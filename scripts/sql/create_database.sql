-- ----------------------------------------------------------------------------
-- 0. Параметры (замените на свои при необходимости)
-- ----------------------------------------------------------------------------
-- Имя базы: srs_context
-- Пользователь приложения: srs_app
-- Пароль приложения: измените ОБЯЗАТЕЛЬНО перед выполнением!

-- ----------------------------------------------------------------------------
-- 1. Создание базы данных
--    (CREATE DATABASE нельзя выполнить внутри транзакции — выполняйте отдельно)
-- ----------------------------------------------------------------------------
-- \connect postgres  -- при необходимости переподключитесь к служебной базе

CREATE DATABASE srs_context
    WITH ENCODING = 'UTF8'
         LC_COLLATE = 'ru_RU.UTF-8'   -- при проблемах с локалью замените на 'C.UTF-8' или 'en_US.UTF-8'
         LC_CTYPE   = 'ru_RU.UTF-8'
         TEMPLATE   = template0;

-- ----------------------------------------------------------------------------
-- 2. Пользователь приложения и права
-- ----------------------------------------------------------------------------
CREATE USER srs_app WITH PASSWORD 'CHANGE_ME_STRONG_PASSWORD';

GRANT CONNECT ON DATABASE srs_context TO srs_app;

